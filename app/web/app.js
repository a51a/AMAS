async function route() {
  hideTip(); document.onkeydown = null;
  const h = location.hash.replace(/^#/, "") || "/";
  const parts = h.split("/").filter(Boolean);
  try {
    if (!parts.length) return await viewHome();
    if (parts[0] === "exp" && parts.length === 2) return await viewDetail(parts[1]);
    if (parts[0] === "exp" && parts[2] === "import") return await viewImport(parts[1]);
    if (parts[0] === "exp" && parts[2] === "compare") return await viewCompare(parts[1]);
    if (parts[0] === "exp" && parts[2] === "interventions") return await viewInterventions(parts[1]);
    if (parts[0] === "session") return await viewSession(parts[1]);
    if (parts[0] === "profiles" && parts[1]) return await viewProfile(parts[1]);
    if (parts[0] === "profiles") return await viewProfiles();
    $view.innerHTML = `<p>Not found. <a href="#/">Home</a></p>`;
  } catch (err) {
    $view.innerHTML = `<p class="error">${esc(err.message)}</p>`;
  }
}
