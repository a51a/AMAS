function showTip(evt, html) {
  $tip.innerHTML = html; $tip.style.display = "block";
  const host = $tip.offsetParent || document.body;
  const x = evt.pageX + 14, y = evt.pageY + 14;
  $tip.style.left = `${Math.min(x, window.innerWidth - $tip.offsetWidth - 12)}px`;
  $tip.style.top = `${y}px`;
}
const hideTip = () => ($tip.style.display = "none");
function bindTips(root) {
  root.querySelectorAll("[data-tip]").forEach((el) => {
    el.addEventListener("mousemove", (e) => showTip(e, el.dataset.tip));
    el.addEventListener("mouseleave", hideTip);
  });
}

// ---------- charts (inline SVG) ----------
function trendChart(summary) {
  const pts = summary.trend.filter((t) => t.direct_share !== null);
  if (!pts.length) return `<p class="muted">No classified sessions yet.</p>`;
  const W = 720, H = 240, L = 44, R = 16, T = 14, B = 34;
  const target = summary.target_share || 0;
  const maxY = Math.max(target * 1.25, ...pts.map((p) => (p.direct_share_ci95 ? p.direct_share_ci95[1] : p.direct_share)), 0.05);
  const x = (i) => L + (pts.length === 1 ? (W - L - R) / 2 : (i * (W - L - R)) / (pts.length - 1));
  const y = (v) => T + (H - T - B) * (1 - v / maxY);
  const ticks = [0, maxY / 2, maxY].map((v) => `<line class="axis" x1="${L}" x2="${W - R}" y1="${y(v)}" y2="${y(v)}"/><text x="${L - 6}" y="${y(v) + 4}" text-anchor="end">${pct(v, 0)}</text>`).join("");
  const band = pts.filter((p) => p.direct_share_ci95).map((p, i) => `<line x1="${x(pts.indexOf(p))}" x2="${x(pts.indexOf(p))}" y1="${y(p.direct_share_ci95[0])}" y2="${y(p.direct_share_ci95[1])}" stroke="var(--direct)" stroke-opacity=".35" stroke-width="6" stroke-linecap="round"/>`).join("");
  const line = pts.map((p, i) => `${i ? "L" : "M"}${x(i)},${y(p.direct_share)}`).join("");
  const dots = pts.map((p, i) => {
    const tip = `<b>${esc(p.checkpoint)}</b> · ${dt(p.captured_at)}<br>Direct ${pct(p.direct_share)} (${p.exposures_eligible} eligible)<br>${ci(p.direct_share_ci95)}<br>vs baseline ${pp(p.change_pp)}`;
    return `<circle cx="${x(i)}" cy="${y(p.direct_share)}" r="5" fill="var(--direct)" stroke="var(--surface)" stroke-width="2"/>
      <rect x="${x(i) - 18}" y="${T}" width="36" height="${H - T - B}" fill="transparent" data-tip="${esc(tip)}"/>
      <text x="${x(i)}" y="${H - 12}" text-anchor="middle">${esc(p.checkpoint)}</text>`;
  }).join("");
  const tline = target ? `<line x1="${L}" x2="${W - R}" y1="${y(target)}" y2="${y(target)}" stroke="var(--target-line)" stroke-dasharray="4 4" stroke-width="1"/>
    <text x="${W - R}" y="${y(target) - 6}" text-anchor="end">Target ${pct(target, 0)}</text>` : "";
  return `<div class="chart"><svg viewBox="0 0 ${W} ${H}" role="img" aria-label="Direct target share by session">${ticks}${tline}${band}<path d="${line}" fill="none" stroke="var(--direct)" stroke-width="2"/>${dots}</svg></div>
    <div class="legend"><span><i class="sw-direct"></i>Direct share (bar = 95% CI)</span><span>Dashed line = target</span></div>`;
}

function distributionChart(summary) {
  const rows = summary.trend.filter((t) => t.exposures_eligible > 0);
  if (!rows.length) return `<p class="muted">No eligible exposures yet.</p>`;
  const W = 720, rowH = 26, L = 110, R = 10, H = rows.length * (rowH + 8) + 4;
  const fill = { direct: "var(--direct)", adjacent: "var(--adjacent)", unrelated: "var(--unrelated)", unknown: "url(#hatch)" };
  const body = rows.map((r, i) => {
    let x0 = L; const yy = i * (rowH + 8);
    const segs = LABELS.map((k) => {
      const v = r.shares[k] || 0; const w = v * (W - L - R);
      if (w <= 0) return "";
      const s = `<rect x="${x0}" y="${yy}" width="${Math.max(w - 2, 1)}" height="${rowH}" rx="3" fill="${fill[k]}" ${k === "unknown" ? 'stroke="var(--unknown)"' : ""} data-tip="${esc(`<b>${r.checkpoint}</b> ${k}: ${pct(v)} (${Math.round(v * r.exposures_eligible)} of ${r.exposures_eligible})`)}"/>`;
      x0 += w; return s;
    }).join("");
    return `<text x="0" y="${yy + 17}">${esc(r.checkpoint)} · n=${r.exposures_eligible}</text>${segs}`;
  }).join("");
  return `<div class="chart"><svg viewBox="0 0 ${W} ${H}" role="img" aria-label="Topic distribution by session">
    <defs><pattern id="hatch" width="4" height="4" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><rect width="4" height="4" fill="var(--surface)"/><line x1="0" y1="0" x2="0" y2="4" stroke="var(--unknown)" stroke-width="2"/></pattern></defs>${body}</svg></div>
    <div class="legend">${LABELS.map((k) => `<span><i class="sw-${k}"></i>${k}</span>`).join("")}</div>`;
}

