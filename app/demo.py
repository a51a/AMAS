"""Synthetic demo experiment. Clearly labelled; never mixed with real data.

DEMO-001 lives in its own experiment with is_demo=1, its own profile and the
mock platform. The UI shows a 'SIMULATED' banner on every demo screen.
"""
from __future__ import annotations

import random
from datetime import datetime, timedelta, timezone

from app.adapters.mock_platform import MockPlatformAdapter
from app.actuator.base import MockActuator
from app.models.schemas import ExperimentCreate
from app.services import accept_sample
from app.storage.repository import Repository
from app.taste_engine.profiles import load_experiment_config, upgrade_legacy_profile

DEMO_ID = "DEMO-001"

# (checkpoint, label, hours relative to intervention, direct_rate, adjacent_rate)
DEMO_SCHEDULE = [
    ("T0", "Baseline A", -30, 0.00, 0.02),
    ("T0", "Baseline B", -6, 0.02, 0.02),
    ("T2", "Immediate", 0.5, 0.16, 0.08),
    ("T3", "+24h", 24, 0.12, 0.08),
    ("T4", "+72h", 72, 0.08, 0.06),
    ("T5", "+7d", 168, 0.06, 0.05),
]


def seed_demo(repo: Repository, *, seed: int = 7, n_per_session: int = 50, reset: bool = True) -> dict:
    if reset and repo.get_experiment(DEMO_ID, missing_ok=True):
        repo.delete_experiment(DEMO_ID)
    _, profile = load_experiment_config()
    profile = profile.model_copy(update={"profile_id": "PRF-DEMO-biathlon", "name": "DEMO Biathlon (simulated)",
                                         "is_demo": True})
    repo.upsert_profile(profile)
    upgrade_legacy_profile(repo, profile)
    repo.create_experiment(ExperimentCreate(
        experiment_id=DEMO_ID, name="Operation Biathlon - SIMULATED DEMO",
        research_question="Demo of the AMAS workflow on synthetic data. Not a research finding.",
        platform="mock", surface="mock_feed", profile_id=profile.profile_id, target_topic="biathlon",
        target_share=0.2, is_demo=True, config={"seed": seed, "note": "Synthetic data generated by MockPlatformAdapter"},
    ))
    rng = random.Random(seed)
    anchor = datetime(2026, 1, 10, 18, 0, tzinfo=timezone.utc)
    exp = repo.get_experiment(DEMO_ID)
    for cp, label, hours, d, a in DEMO_SCHEDULE:
        s = repo.create_session(DEMO_ID, checkpoint=cp, capture_method="synthetic", label=label,
                                captured_at=(anchor + timedelta(hours=hours)).isoformat())
        for row in MockPlatformAdapter.simulate_feed(rng, n_per_session, direct_rate=d, adjacent_rate=a):
            repo.add_observation(s["session_id"], row)
        repo.update_session(s["session_id"], {"status": "classified"})
        if cp == "T0":
            accept_sample(repo, s["session_id"], deviation_note="Simulated demo data; not human-reviewed.")
    act = MockActuator(MockPlatformAdapter())
    repo.add_intervention(DEMO_ID, act.plan(exp, "simulated_boost", {"topic": "biathlon",
                                                                     "completed_at": anchor.isoformat()},
                                            "Simulated biathlon interest boost"))
    return repo.get_experiment(DEMO_ID)
